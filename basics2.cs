using System;

// консольная программа для вывода симметричного узора из символов X
class Program
{
    // рисует узор размером n на n символов, вычисляя две симметричные позиции X в каждой строке
    // n — размер квадратной области вывода
    static void Draw(int n)
    {
        // индекс середины области (целочисленное деление)
        int mid = n / 2;

        // внешний цикл перебирает строки сверху вниз
        for (int i = 0; i < n; i++)
        {
            // расстояние от текущей строки до середины определяет первую позицию X
            int a = Math.Abs(mid - i);
            // вторая позиция зеркальна первой относительно вертикальной оси
            int b = n - 1 - a;

            // внутренний цикл перебирает столбцы текущей строки
            for (int j = 0; j < n; j++)
            {
                // в рассчитанных позициях печатаем X, в остальных — пробел
                if (j == a || j == b)
                    Console.Write("X");
                else
                    Console.Write(" ");
            }

            // после заполнения строки переходим на следующую
            Console.WriteLine();
        }
    }

    // метод Main: выводит узор размером 5 на 5
    static void Main()
    {
        Draw(5);
    }
}